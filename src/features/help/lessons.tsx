/**
 * Уроки «Обучения»: по одному на каждый блок сайта. Текст урока объясняет блок, а кнопка «Показать на сайте»
 * запускает тур с тем же id (src/features/tour/tours.ts) – он подсвечивает элементы и сам выполняет действия.
 */
export interface Lesson {
  id: string;
  title: string;
  block: string;
  minutes: number;
  lead: string;
  body: (objectId: string) => ReactNode;
}

const P = ({ children }: { children: ReactNode }) => <p>{children}</p>;
const H = ({ children }: { children: ReactNode }) => <h3 className="pt-2 text-h3">{children}</h3>;
const B = ({ children }: { children: ReactNode }) => <b className="font-semibold text-text-primary">{children}</b>;

function Table({ rows }: { rows: [ReactNode, ReactNode][] }) {
  return (
    <div role="table" className="overflow-hidden rounded-md border border-border">
      {rows.map(([a, b], i) => (
        <div role="row" key={i} className="grid gap-x-4 gap-y-0.5 border-b border-border px-4 py-2.5 last:border-b-0 sm:grid-cols-[minmax(9rem,13rem)_1fr]">
          <span role="cell" className="font-medium text-text-primary">
            {a}
          </span>
          <span role="cell">{b}</span>
        </div>
      ))}
    </div>
  );
}

function Tip({ title, warn, children }: { title: string; warn?: boolean; children: ReactNode }) {
  const Icon = warn ? TriangleAlert : Lightbulb;
  return (
    <div className={warn ? 'flex gap-3 rounded-md border-l-[3px] border-warning bg-warning-subtle px-4 py-3' : 'flex gap-3 rounded-md border-l-[3px] border-accent bg-accent-subtle px-4 py-3'}>
      <Icon className={warn ? 'mt-0.5 size-4 shrink-0 text-warning' : 'mt-0.5 size-4 shrink-0 text-accent-strong'} aria-hidden />
      <span className="flex flex-col gap-0.5">
        <b className="font-semibold text-text-primary">{title}</b>
        <span>{children}</span>
      </span>
    </div>
  );
}

function Where({ to, label }: { to: string; label: string }) {
  return (
    <Link to={to} className="inline-flex items-center gap-1.5 self-start text-body-sm font-medium text-accent-strong hover:underline">
      Где это: {label} <ArrowRight className="size-4" aria-hidden />
    </Link>
  );
}

const Ol = ({ items }: { items: ReactNode[] }) => (
  <ol className="flex list-decimal flex-col gap-1.5 pl-5 marker:text-text-muted">
    {items.map((x, i) => (
      <li key={i}>{x}</li>
    ))}
  </ol>
);

