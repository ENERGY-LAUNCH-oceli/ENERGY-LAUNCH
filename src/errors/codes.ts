/** «Нет подключения» – не код HTTP: ответа сервера нет вовсе. */
export const OFFLINE_INFO: StatusInfo = {
  code: 0,
  name: 'Offline',
  title: 'Нет подключения к интернету',
  text: 'Браузер не может связаться с сервером: сеть отключена или недоступна.',
  hint: 'Проверьте Wi-Fi или кабель. Как только связь вернётся, работа продолжится сама.',
};

export const statusClass = (code: number): StatusClass => (code === 0 ? 'offline' : code < 200 ? 'info' : code < 300 ? 'success' : code < 400 ? 'redirect' : code < 500 ? 'client' : 'server');

/** Описание кода; неизвестный код из допустимого диапазона – общее описание его класса. */
export function statusInfo(code: number): StatusInfo | null {
  if (code === 0) return OFFLINE_INFO;
  const known = STATUS_CODES.find((x) => x.code === code);
  if (known) return known;
  if (!Number.isInteger(code) || code < 100 || code > 599) return null;
  const cls = statusClass(code);
  return { code, name: 'Unknown', title: `Код ${code}`, text: `Нестандартный код из группы «${CLASS_TITLE[cls]}».`, hint: cls === 'client' || cls === 'server' ? RETRY : 'Обновите страницу.' };
}

